def get_chapter(chapter_id: int) -> StoryChapter | None:
    """Получить главу по ID."""
    return STORY_CHAPTERS.get(chapter_id)


def get_all_chapters() -> list[StoryChapter]:
    """Получить все главы в порядке возрастания."""
    return [STORY_CHAPTERS[i] for i in sorted(STORY_CHAPTERS.keys())]


def get_available_chapters(player_level: int) -> list[StoryChapter]:
    """Получить доступные главы для уровня игрока."""
    return [
        chapter for chapter in get_all_chapters()
        if chapter.is_unlocked(player_level)
    ]
