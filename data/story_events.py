"""Сюжетные события и кат-сцены."""
from dataclasses import dataclass
from typing import Optional


@dataclass
class StoryEvent:
    """Сюжетное событие."""
    event_id: str
    title: str
    description: str  # Основной текст события
    trigger_chapter: int  # При какой главе срабатывает
    trigger_on_complete: bool = False  # True = после завершения главы, False = перед началом
    choices: list[tuple[str, str]] = None  # (текст выбора, effect_id)
    one_time: bool = True  # Показать только один раз

    def __post_init__(self):
        if self.choices is None:
            self.choices = []


