def get_event(event_id: str) -> StoryEvent | None:
    """Получить событие по ID."""
    return STORY_EVENTS.get(event_id)


def get_events_for_chapter(chapter: int, on_complete: bool = False) -> list[StoryEvent]:
    """Получить все события для главы."""
    return [
        event for event in STORY_EVENTS.values()
        if event.trigger_chapter == chapter and event.trigger_on_complete == on_complete
    ]
